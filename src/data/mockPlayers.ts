/**
 * Finds players matching a target Elo rating within a specified tolerance
 */
export function findMatchingOpponents(
  userRating: number,
  timeControl: 'bullet' | 'blitz' | 'rapid' | 'classical',
  tolerance: number = 75
): BotPlayer[] {
  const getRatingForTc = (p: BotPlayer) => {
    switch (timeControl) {
      case 'bullet':
        return p.bulletRating;
      case 'blitz':
        return p.blitzRating;
      case 'rapid':
        return p.rapidRating;
      case 'classical':
        return p.classicalRating;
    }
  };

  const pool = [...SIMULATED_PLAYERS].sort((a, b) => {
    const diffA = Math.abs(getRatingForTc(a) - userRating);
    const diffB = Math.abs(getRatingForTc(b) - userRating);
    return diffA - diffB;
  });

  const matched = pool.filter((p) => Math.abs(getRatingForTc(p) - userRating) <= tolerance);
  return matched.length > 0 ? matched : pool.slice(0, 3);
}
